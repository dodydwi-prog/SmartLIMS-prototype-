export function resolveIdentifierToEmail(identifier: string): string {
  const clean = identifier.trim().toLowerCase();
  if (clean.includes('@')) return clean;
  const matched = DEMO_USERS.find((u) => u.username?.toLowerCase() === clean);
  if (matched) return matched.email.toLowerCase();
  return `${clean}@users.smartlims.id`;
}

